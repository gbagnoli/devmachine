//! Reconcile image unit ownership without overwriting administrator definitions.
use crate::{
    files::{FileMutationResource, FileReadResource, Ownership},
    system::ServiceResource,
};
use std::path::{Path, PathBuf};

pub struct Unit {
    pub name: &'static str,
    pub content: String,
}

impl Unit {
    pub fn is_timer(&self) -> bool {
        self.name
            .rsplit_once('.')
            .is_some_and(|(_, kind)| kind == "timer")
    }

    pub fn is_service(&self) -> bool {
        self.name
            .rsplit_once('.')
            .is_some_and(|(_, kind)| kind == "service")
    }
}

pub struct LegacyReceipt {
    pub path: PathBuf,
    pub revisions: Vec<Vec<u8>>,
}

#[derive(Debug, thiserror::Error)]
pub enum Error {
    #[error(transparent)]
    File(#[from] crate::files::FileError),
    #[error(transparent)]
    System(#[from] crate::system::SystemError),
    #[error("image unit ownership conflict: {0}")]
    Conflict(String),
}

/// Returns false only when this group has no image definitions yet. Legacy
/// candidates are exact known generated bytes, never inferred from filenames.
pub fn reconcile<S, F>(
    system: &S,
    files: &F,
    group: &str,
    vendor: &[Unit],
    legacy: &[Unit],
    legacy_receipt: Option<&LegacyReceipt>,
) -> Result<bool, Error>
where
    S: ServiceResource + ?Sized,
    F: FileReadResource + FileMutationResource + ?Sized,
{
    if group.is_empty()
        || !group
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-')
    {
        return Err(Error::Conflict("invalid unit group".into()));
    }
    let mut present = 0;
    for unit in vendor {
        let path = Path::new("/usr/lib/systemd/system").join(unit.name);
        if let Some(bytes) = files.read_regular_file(&path)? {
            if bytes != unit.content.as_bytes() {
                return Err(Error::Conflict(format!(
                    "{} differs from this Skillet release; update the image first",
                    path.display()
                )));
            }
            present += 1;
        }
    }
    if present == 0 {
        return Ok(false);
    }
    if present != vendor.len() {
        return Err(Error::Conflict("incomplete vendor unit group".into()));
    }
    let mut retired = Vec::new();
    let mut receipt = Vec::new();
    for unit in vendor {
        receipt.extend_from_slice(unit.name.as_bytes());
        receipt.push(0);
        receipt.extend_from_slice(unit.content.as_bytes());
        let path = Path::new("/etc/systemd/system").join(unit.name);
        let archive = PathBuf::from(format!("{}.skillet-legacy", path.display()));
        let current = files.read_regular_file(&path)?;
        let previous = files.read_regular_file(&archive)?;
        if let Some(bytes) = current.as_ref() {
            if !legacy.iter().any(|candidate| {
                candidate.name == unit.name && candidate.content.as_bytes() == bytes
            }) {
                return Err(Error::Conflict(format!("{} or its recovery copy contains unknown edits; preserve and inspect before migration", path.display())));
            }
        }
        if let Some(bytes) = current {
            if previous.as_ref().is_some_and(|old| old != &bytes) {
                return Err(Error::Conflict(format!(
                    "recovery copy differs: {}",
                    archive.display()
                )));
            }
            retired.push((path, archive, bytes));
        }
    }
    let state_dir = Path::new("/var/lib/skillet/vendor-units");
    let state = state_dir.join(format!("{group}.applied"));
    let pending = files.read_regular_file(&state)?.as_deref() != Some(receipt.as_slice());
    if !retired.is_empty() {
        if let Some(expected) = legacy_receipt {
            verify_receipt(files, expected)?;
        }
    }
    if pending || !retired.is_empty() {
        for unit in vendor.iter().filter(|unit| unit.is_service()) {
            if system.service_is_busy(unit.name)? {
                return Err(Error::Conflict(format!(
                    "{} is busy; retry after completion",
                    unit.name
                )));
            }
        }
        for unit in vendor.iter().filter(|unit| unit.is_timer()) {
            system.service_stop(unit.name)?;
        }
        for unit in vendor.iter().filter(|unit| unit.is_service()) {
            if system.service_is_busy(unit.name)? {
                return Err(Error::Conflict(format!(
                    "{} started while stopping timers; retry to reactivate",
                    unit.name
                )));
            }
        }
        for (path, archive, bytes) in retired {
            files.retire_file(&path, &bytes, &archive)?;
        }
        system.daemon_reload()?;
        for unit in vendor.iter().filter(|unit| unit.is_timer()) {
            system.service_reenable(unit.name)?;
        }
        let root = Ownership::named(Some("root"), Some("root"));
        files.ensure_directory(state_dir, Some(0o755), &root)?;
        files.ensure_file(&state, &receipt, Some(0o644), &root)?;
    }
    Ok(true)
}

fn verify_receipt<F: FileReadResource + ?Sized>(
    files: &F,
    expected: &LegacyReceipt,
) -> Result<(), Error> {
    let actual = files.read_regular_file(&expected.path)?;
    if !actual
        .as_ref()
        .is_some_and(|bytes| expected.revisions.contains(bytes))
    {
        return Err(Error::Conflict(format!(
            "legacy receipt differs or is absent: {}",
            expected.path.display()
        )));
    }
    Ok(())
}

